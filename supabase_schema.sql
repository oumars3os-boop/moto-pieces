-- 4. TRIGGER D'INSCRIPTION AUTOMATIQUE SUPABASE AUTH -> PUBLIC.USERS
-- ====================================================================

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.users (id, nom, tel, role)
  VALUES (
    NEW.id,
    COALESCE(NEW.raw_user_meta_data->>'nom', NEW.email),
    COALESCE(NEW.phone, NEW.raw_user_meta_data->>'tel', ''),
    COALESCE(NEW.raw_user_meta_data->>'role', 'vendeur')
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

